import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
await mkdir('reports/spring-ui', { recursive: true });
const browser = await chromium.launch({ headless:true, executablePath:'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe' });
const desktop = await browser.newPage({ viewport:{ width:1440,height:1000 } });
await desktop.goto('http://localhost:8082',{ waitUntil:'networkidle' });
await desktop.screenshot({ path:'reports/spring-ui/home-desktop.png',fullPage:true });
await desktop.goto('http://localhost:8082/board',{ waitUntil:'networkidle' });
await desktop.screenshot({ path:'reports/spring-ui/board-desktop.png',fullPage:true });
const mobile = await browser.newPage({ viewport:{ width:390,height:844 } });
await mobile.goto('http://localhost:8082',{ waitUntil:'networkidle' });
await mobile.screenshot({ path:'reports/spring-ui/home-mobile.png',fullPage:true });
await browser.close();
